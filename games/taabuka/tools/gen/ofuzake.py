def T(kind, a):
    if kind == 'mood':      return (f"採点されると場の状態を「{a}」にする", [{"when": "採点時", "do": [{"場の状態": a}]}])
    if kind == 'moodS':     m, n = a; return (f"採点されると場の状態を「{m}」にする。強さ{{+{n}}}", [{"when": "採点時", "do": [{"場の状態": m}, {"強さ": n}]}])
    if kind == 'moodM':     m, n = a; return (f"採点されると場の状態を「{m}」にする。倍率{{+{n}}}", [{"when": "採点時", "do": [{"場の状態": m}, {"倍率": n}]}])
    if kind == 'ifX':       m, x = a; return (f"場の状態が「{m}」なら倍率{{x{x}}}", [{"when": "採点時", "if": {"場の状態": m}, "do": [{"掛け": x}]}])
    if kind == 'ifS':       m, n = a; return (f"場の状態が「{m}」なら強さ{{+{n}}}", [{"when": "採点時", "if": {"場の状態": m}, "do": [{"強さ": n}]}])
    if kind == 'anyS':      return (f"場の状態が何かなら強さ{{+{a}}}", [{"when": "採点時", "if": {"場の状態": "何か"}, "do": [{"強さ": a}]}])
    if kind == 'anyM':      return (f"場の状態が何かなら倍率{{+{a}}}", [{"when": "採点時", "if": {"場の状態": "何か"}, "do": [{"倍率": a}]}])
    if kind == 'held':      return (f"ターンの終わりに手札にあると、場の状態を「{a}」にする", [{"when": "ターン終了", "do": [{"場の状態": a}]}])
    if kind == 'disc':      return (f"流すと場の状態を「{a}」にして{{d1}}枚引く", [{"when": "流した時", "do": [{"場の状態": a}, {"引く": 1}]}])
    if kind == 'start':     return (f"戦闘の始めに手札にあると、場の状態を「{a}」にする", [{"when": "戦闘開始", "do": [{"場の状態": a}]}])
    if kind == 'moodZ':     m, n = a; return (f"採点されると場の状態を「{m}」にする。宿銭{{+{n}}}", [{"when": "採点時", "do": [{"場の状態": m}, {"宿銭": n}]}])
    if kind == 'moodH':     m, n = a; return (f"採点されると場の状態を「{m}」にする。体力{{+{n}}}", [{"when": "採点時", "do": [{"場の状態": m}, {"体力": n}]}])
    if kind == 'ifXmood':   m, x, m2 = a; return (f"場の状態が「{m}」なら倍率{{x{x}}}。採点されると場の状態を「{m2}」にする", [{"when": "採点時", "if": {"場の状態": m}, "do": [{"掛け": x}]}, {"when": "採点時", "do": [{"場の状態": m2}]}])
    if kind == 'S':         return (f"強さ{{+{a}}}", [{"when": "採点時", "do": [{"強さ": a}]}])
    if kind == 'Z':         return (f"採点されると宿銭{{+{a}}}", [{"when": "採点時", "do": [{"宿銭": a}]}])
    if kind == 'draw':      return (f"採点されると{{d{a}}}枚引く", [{"when": "採点時", "do": [{"引く": a}]}])
    raise ValueError(kind)

