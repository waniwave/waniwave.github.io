def main():
    out = ["# おふざけ札（tools/gen/ofuzake.py で作る。手で直さない）。普通の札の山には入らず、極まれに「おふざけ枠」で出る", ""]
    seen = set()
    for i, (name, cats, grade, kind, arg, show, flavor) in enumerate(C, 1):
        assert name not in seen, name
        seen.add(name)
        text, fx = T(kind, arg)
        out.append(f"- id: oz_{i:03d}")
        out.append(f"  name: {json.dumps(name, ensure_ascii=False)}")
        out.append(f"  cat: {json.dumps(cats, ensure_ascii=False)}")
        out.append(f"  grade: {grade}")
        out.append(f"  text: {json.dumps(text, ensure_ascii=False)}")
        out.append(f"  flavor: {json.dumps(flavor, ensure_ascii=False)}")
        out.append("  fx:")
        for f in fx: out.append(f"    - {json.dumps(f, ensure_ascii=False)}")
        if show: out.append(f"  show: {json.dumps(show, ensure_ascii=False)}")
        out.append("")
    p = os.path.join(os.path.dirname(__file__), '..', '..', 'content', 'sets', 'ofuzake', 'cards.yaml')
    open(p, 'w').write('\n'.join(out))
    print(len(C), 'cards')

main()
