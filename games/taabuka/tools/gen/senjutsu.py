def main():
    out = ["# 戦術の札（tools/gen/senjutsu.py で作る。手で直さない）。論客を降参させる札", ""]
    n = 0
    seen = set()
    for cat, rows in C.items():
        for (name, sub, grade, kind, arg, flavor) in rows:
            assert name not in seen, name
            seen.add(name)
            n += 1
            text, fx = T(kind, arg)
            cats = [cat] + ([sub] if sub else [])
            out += [f"- id: sj_{n:03d}", f"  name: {json.dumps(name, ensure_ascii=False)}", f"  cat: {json.dumps(cats, ensure_ascii=False)}", f"  grade: {grade}",
                    f"  text: {json.dumps(text, ensure_ascii=False)}", f"  flavor: {json.dumps(flavor, ensure_ascii=False)}", "  fx:"]
            out += [f"    - {json.dumps(f, ensure_ascii=False)}" for f in fx]
            out.append("")
    d = os.path.join(os.path.dirname(__file__), '..', '..', 'content', 'sets', 'senjutsu')
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'cards.yaml'), 'w').write('\n'.join(out))
    open(os.path.join(d, 'set.yaml'), 'w').write('id: senjutsu\nname: 戦術\nunlock: { start: true }\ncolor: "#5a7a9a"\nkeywords: []\nintro: 論破のほかの勝ち方。呆れさせる、共感させる、論点をずらす、受けで封殺する、番付から落とす、耐えて根負けさせる。\n')
    print(n, 'cards')

main()
