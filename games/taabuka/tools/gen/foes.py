def main():
    cats = yaml.safe_load(open(os.path.join(ROOT, 'balance', 'tiers.yaml')))['categories']
    out = ["# テーマの穴の層ごとの専用の論客（tools/gen/foes.py で作る。手で直さない）", ""]
    seen = set()
    for dg, layers in F.items():
        for k, rows in enumerate(layers):
            assert len(rows) == 5, (dg, k)
            ids = []
            for j, (name, cat, yk, typ, intro, defeat) in enumerate(rows):
                if cat == '全': cat = '宿'
                assert cat in cats, (name, cat)
                assert name not in seen, name
                seen.add(name)
                eid = f"en_f_{dg}_{k+1}{'abcde'[j]}"
                ids.append(eid)
                elite = j == 4
                hp, atk, acts = (EA if elite else A)[typ]
                d = dict(id=eid, name=name, layer=[], kind='精鋭' if elite else '通常', hp=hp, atk=atk, acts=acts, line=intro,
                         cat=cat, **{'yield': {'kind': yk}}, talk={'intro': [intro], 'defeat': [defeat]})
                out.append('- ' + json.dumps(d, ensure_ascii=False))
            # 層のファイルの groups と elites を書き換える
            p = os.path.join(ROOT, 'layers', f'dg_{dg}_{k+1}.yaml')
            L = yaml.safe_load(open(p))
            n = ids[:4]
            L['groups'] = [[n[0]], [n[1]], [n[2]], [n[3]], [n[0], n[1]], [n[2], n[3]], [n[0], n[2]], [n[1], n[3], n[0]]]
            L['elites'] = [ids[4]] + [e for e in L['elites'] if not e.startswith('en_f_')][:1]
            src = open(p).read()
            head = ''.join(l for l in src.splitlines(True) if l.startswith('#'))
            open(p, 'w').write(head + yaml.safe_dump(L, allow_unicode=True, sort_keys=False, width=200, default_flow_style=None))
    open(os.path.join(ROOT, 'enemies', 'dg_foes.yaml'), 'w').write('\n'.join(out) + '\n')
    print(len(seen), 'foes')

main()
