def bind_of(gs): return '・'.join(DESC[g['k']](g) for g in gs)

# 前からいた穴の層主（enemies/dungeons.yaml）は同じ id で作り直す（フレーバーと証言をそのまま使う）。古い定義は dungeons.yaml から外す
OLD = {('yatai', 'oyaji'): 'en_dg_oyaji', ('kousha', 'kouchou'): 'en_dg_kouchou', ('yukemuri', 'bandai'): 'en_dg_bandai', ('gesen', 'rensho'): 'en_dg_rensho',
       ('koujou', 'kojocho'): 'en_dg_kojocho', ('kakolog', '1001'): 'en_dg_1001', ('urayama', 'kannushi'): 'en_dg_kannushi', ('yaneura', 'yanenoura'): 'en_dg_yanenoura'}

def make(dg, row, kind):
    (tail, name, cat, yk, hp, atk, acts, gs, intro, defeat) = row
    return dict(id=OLD.get((dg, tail), f"en_b_{dg}_{tail}"), name=name, layer=[], kind=kind, hp=hp, atk=atk, acts=acts, custom='仕掛け', params={'仕掛け': gs},
                bind=bind_of(gs), line=intro, cat=cat, **{'yield': {'kind': yk}}, talk={'intro': [intro], 'defeat': [defeat]})

def patch(fname, ids):
    p = os.path.join(ROOT, 'layers', fname)
    L = yaml.safe_load(open(p))
    L['bosses'] = ids
    head = ''.join(l for l in open(p).read().splitlines(True) if l.startswith('#'))
    open(p, 'w').write(head + yaml.safe_dump(L, allow_unicode=True, sort_keys=False, width=200, default_flow_style=None))

def main():
    out = ["# 主（tools/gen/bosses.py で作る。手で直さない）。仕掛けは content/enemies/custom/gimmick.js", ""]
    for dg, rows in B.items():
        ds = [make(dg, r, '層主') for r in rows]
        out += ['- ' + json.dumps(d, ensure_ascii=False) for d in ds]
        for k in range(3): patch(f'dg_{dg}_{k + 1}.yaml', [ds[k]['id']])
        patch(f'dg_{dg}_soko.yaml', [ds[3]['id'], ds[4]['id']])
    deep = [make('honko', r, '層主') for r in DEEP]
    out += ['- ' + json.dumps(d, ensure_ascii=False) for d in deep]
    patch('beyond.yaml', [d['id'] for d in deep])
    open(os.path.join(ROOT, 'enemies', 'bosses.yaml'), 'w').write('\n'.join(out) + '\n')
    p = os.path.join(ROOT, 'enemies', 'dungeons.yaml')
    olds = [e for e in (yaml.safe_load(open(p)) or []) if e['id'] not in OLD.values()]
    open(p, 'w').write('# テーマの穴の層主（tools/gen/dungeons.py）。作り直した主は bosses.yaml へ移した（tools/gen/bosses.py）\n' + (yaml.safe_dump(olds, allow_unicode=True, sort_keys=False, width=200) if olds else '[]\n'))
    print(len(B) * 5 + len(DEEP), 'bosses')

main()
